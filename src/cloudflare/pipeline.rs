impl terrars::Referable for Pipeline {
    fn extract_ref(&self) -> std::string::String {
        format!("{}.{}", self.0.extract_resource_type(), self.0.extract_tf_id())
    }
}

impl terrars::Resource for Pipeline { }

impl terrars::ToListMappable for Pipeline {
    type O = terrars::ListRef<PipelineRef>;

    fn do_map(self, base: std::string::String) -> Self::O {
        self.0.data.borrow_mut().for_each = std::option::Option::Some(format!("${{{}}}", base));
        terrars::ListRef::new(self.0.shared.clone(), self.extract_ref())
    }
}

impl terrars::Resource_ for Pipeline_ {
    fn extract_resource_type(&self) -> std::string::String {
        "cloudflare_pipeline".into()
    }

    fn extract_tf_id(&self) -> std::string::String {
        self.tf_id.clone()
    }

    fn extract_value(&self) -> serde_json::Value {
        serde_json::to_value(&self.data).unwrap()
    }
}

pub struct BuildPipeline {
    pub tf_id: std::string::String,
    #[doc = "Specifies the public ID of the account."]
    pub account_id: terrars::PrimField<std::string::String>,
    #[doc = "Specifies the name of the Pipeline."]
    pub name: terrars::PrimField<std::string::String>,
    #[doc = "Specifies SQL for the Pipeline processing flow."]
    pub sql: terrars::PrimField<std::string::String>,
}

impl BuildPipeline {
    pub fn build(self, stack: &mut terrars::Stack) -> Pipeline {
        let out = Pipeline(std::rc::Rc::new(Pipeline_ {
            shared: stack.shared.clone(),
            tf_id: self.tf_id,
            data: std::cell::RefCell::new(PipelineData_ {
                depends_on: core::default::Default::default(),
                provider: std::option::Option::None,
                lifecycle: core::default::Default::default(),
                for_each: std::option::Option::None,
                provisioner: core::default::Default::default(),
                account_id: self.account_id,
                name: self.name,
                sql: self.sql,
            }),
        }));
        stack.add_resource(out.0.clone());
        out
    }
}

